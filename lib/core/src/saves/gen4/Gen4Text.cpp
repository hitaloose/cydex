void gen4_text_decode(const uint8_t *data, size_t chars, char *out, size_t out_size) {
  size_t pos = 0;
  for (size_t i = 0; i < chars; i++) {
    uint16_t c = read_u16_le(data + 2 * i);
    if (c == 0xFFFF) break;
    uint16_t u = to_unicode(c);
    char buf[3];
    size_t n = utf8(u ? u : '?', buf);
    if (pos + n >= out_size) break;
    memcpy(out + pos, buf, n);
    pos += n;
  }
  out[pos] = '\0';
}

void gen4_text_encode(const char *text, uint8_t *out, size_t chars) {
  memset(out, 0, chars * 2);
  size_t i = 0;
  for (; text[i] && i + 1 < chars; i++) {
    uint16_t code = 0x1AC;  // ?
    for (uint16_t k = 0; k <= kLast - kFirst; k++) {
      if (kLatin[k] == (uint8_t)text[i]) {
        code = (uint16_t)(kFirst + k);
        break;
      }
    }
    out[2 * i] = (uint8_t)code;
    out[2 * i + 1] = (uint8_t)(code >> 8);
  }
  out[2 * i] = 0xFF;
  out[2 * i + 1] = 0xFF;
}
