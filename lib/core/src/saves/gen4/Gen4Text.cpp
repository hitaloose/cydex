constexpr uint16_t kLast = kFirst + sizeof(kLatin) / sizeof(kLatin[0]) - 1;

uint16_t to_unicode(uint16_t c) {
  if (c >= kFirst && c <= kLast) return kLatin[c - kFirst];
  switch (c) {
    case 0x0E5: return 0x2026;  // …
    case 0x0E7: return '/';
    case 0x0EE: return 0x2642;  // ♂
    case 0x0EF: return 0x2640;  // ♀
    case 0x0F2: return 0xD7;    // ×
    case 0x0F3: return 0xF7;    // ÷
    default: return 0;
  }
}

size_t utf8(uint16_t u, char *out) {
  if (u < 0x80) {
    out[0] = (char)u;
    return 1;
  }
  if (u < 0x800) {
    out[0] = (char)(0xC0 | (u >> 6));
    out[1] = (char)(0x80 | (u & 0x3F));
    return 2;
  }
  out[0] = (char)(0xE0 | (u >> 12));
  out[1] = (char)(0x80 | ((u >> 6) & 0x3F));
  out[2] = (char)(0x80 | (u & 0x3F));
  return 3;
}

